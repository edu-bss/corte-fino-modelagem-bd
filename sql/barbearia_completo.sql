-- ============================================================
-- CONSULTAS GERENCIAIS - CORTE FINO (PostgreSQL)
-- Criterios adotados:
--  * Faturamento de servicos = servicos REALIZADOS em atendimentos CONCLUIDO,
--    valorizados por AGENDAMENTO_SERVICO.preco_praticado
--  * Faturamento de produtos = itens de VENDA com pago = TRUE,
--    valorizados por ITEM_VENDA.preco_praticado
-- ============================================================

-- [Q1] Faturamento por mes (servicos + produtos)
WITH receitas AS (
    SELECT TO_CHAR(a.data_hora_inicio, 'YYYY-MM') AS mes,
           aus.preco_praticado AS servicos,
           0 AS produtos
    FROM agendamento_servico aus
    JOIN agendamento a ON a.id_agendamento = aus.id_agendamento
    WHERE a.status = 'CONCLUIDO'
      AND aus.realizado = TRUE
    UNION ALL
    SELECT TO_CHAR(v.data_hora, 'YYYY-MM'),
           0,
           iv.quantidade * iv.preco_praticado
    FROM item_venda iv
    JOIN venda v ON v.id_venda = iv.id_venda
    WHERE v.pago = TRUE
)
SELECT mes,
       SUM(servicos) AS faturamento_servicos,
       SUM(produtos) AS faturamento_produtos,
       SUM(servicos) + SUM(produtos) AS faturamento_total
FROM receitas
GROUP BY mes
ORDER BY mes;

-- [Q2] Servicos mais realizados
SELECT s.nome AS servico,
       COUNT(*) AS vezes_realizado,
       SUM(aus.preco_praticado) AS receita
FROM agendamento_servico aus
JOIN agendamento a ON a.id_agendamento = aus.id_agendamento
JOIN servico s ON s.id_servico = aus.id_servico
WHERE a.status = 'CONCLUIDO'
  AND aus.realizado = TRUE
GROUP BY s.id_servico, s.nome
ORDER BY vezes_realizado DESC, s.nome;

-- [Q3] Produtos mais vendidos (vendas pagas)
SELECT p.nome AS produto,
       SUM(iv.quantidade) AS unidades_vendidas,
       SUM(iv.quantidade * iv.preco_praticado) AS receita
FROM item_venda iv
JOIN venda v ON v.id_venda = iv.id_venda

-- ============================================================
-- 1. CLIENTE
-- ============================================================

CREATE TABLE cliente (
    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(100) NOT NULL,
    telefone VARCHAR(20) NOT NULL,
    email VARCHAR(120),
    data_cadastro DATE NOT NULL DEFAULT CURRENT_DATE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_cliente
        PRIMARY KEY (id_cliente)
);


-- ============================================================
-- 2. PROFISSIONAL
-- ============================================================

CREATE TABLE profissional (
    id_profissional INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(100) NOT NULL,
    telefone VARCHAR(20),
    data_cadastro DATE NOT NULL DEFAULT CURRENT_DATE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_profissional
        PRIMARY KEY (id_profissional)
);


-- ============================================================
-- 3. SERVICO
-- ============================================================

CREATE TABLE servico (
    id_servico INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(100) NOT NULL,
    descricao VARCHAR(255),
    categoria VARCHAR(50) NOT NULL,
    preco_atual DECIMAL(10,2) NOT NULL,
    duracao_prevista_min INTEGER NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_servico
        PRIMARY KEY (id_servico),

    CONSTRAINT ck_servico_preco
        CHECK (preco_atual > 0),

    CONSTRAINT ck_servico_duracao
        CHECK (duracao_prevista_min > 0)
);

-- ============================================================
-- 4. AGENDAMENTO
-- ============================================================
CREATE TABLE agendamento (
    id_agendamento INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_cliente INTEGER NOT NULL,
    id_profissional INTEGER NOT NULL,
    data_hora_inicio TIMESTAMP NOT NULL,
    status VARCHAR(15) NOT NULL DEFAULT 'AGENDADO',
    pago BOOLEAN,
    observacao VARCHAR(255),

    CONSTRAINT pk_agendamento
        PRIMARY KEY (id_agendamento),

    CONSTRAINT fk_agendamento_cliente
        FOREIGN KEY (id_cliente)
        REFERENCES cliente (id_cliente),

    CONSTRAINT fk_agendamento_profissional
        FOREIGN KEY (id_profissional)
        REFERENCES profissional (id_profissional),

    CONSTRAINT ck_agendamento_status
        CHECK (
            status IN (
                'AGENDADO',
                'CONCLUIDO',
                'CANCELADO'
            )
        ),

    CONSTRAINT ck_agendamento_pagamento
        CHECK (
            status NOT IN (
                'AGENDADO',
                'CONCLUIDO',
                'CANCELADO'
            )
            OR (
                status = 'CONCLUIDO'
                AND pago IS TRUE
            )
            OR (
                status IN ('AGENDADO', 'CANCELADO')
                AND pago IS NULL
            )
        )
);

-- ============================================================
-- 5. AGENDAMENTO_SERVICO
-- ============================================================
CREATE TABLE agendamento_servico (
    id_agendamento_servico INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_agendamento INTEGER NOT NULL,
    id_servico INTEGER NOT NULL,
    agendado BOOLEAN NOT NULL DEFAULT TRUE,
    realizado BOOLEAN NOT NULL DEFAULT FALSE,
    preco_praticado DECIMAL(10,2) NOT NULL,

    CONSTRAINT pk_agendamento_servico
        PRIMARY KEY (id_agendamento_servico),

    CONSTRAINT fk_agendamento_servico_agendamento
        FOREIGN KEY (id_agendamento)
        REFERENCES agendamento (id_agendamento),

    CONSTRAINT fk_agendamento_servico_servico
        FOREIGN KEY (id_servico)
        REFERENCES servico (id_servico),

    CONSTRAINT uq_agendamento_servico
        UNIQUE (id_agendamento, id_servico),

    CONSTRAINT ck_agendamento_servico_situacao
        CHECK (agendado = TRUE OR realizado = TRUE),

    CONSTRAINT ck_agendamento_servico_preco
        CHECK (preco_praticado > 0)
);

-- ============================================================
-- 6. PRODUTO
-- ============================================================
CREATE TABLE produto (
    id_produto INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(100) NOT NULL,
    descricao VARCHAR(255),
    categoria VARCHAR(50) NOT NULL,
    preco_atual DECIMAL(10,2) NOT NULL,
    estoque_minimo INTEGER NOT NULL DEFAULT 0,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_produto
        PRIMARY KEY (id_produto),

    CONSTRAINT ck_produto_preco
        CHECK (preco_atual > 0),

    CONSTRAINT ck_produto_estoque_minimo
        CHECK (estoque_minimo >= 0)
);

-- ============================================================
-- 7. VENDA
-- ============================================================
CREATE TABLE venda (
    id_venda INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_cliente INTEGER NOT NULL,
    data_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    pago BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT pk_venda
        PRIMARY KEY (id_venda),

    CONSTRAINT fk_venda_cliente
        FOREIGN KEY (id_cliente)
        REFERENCES cliente (id_cliente)
);

-- ============================================================
-- 8. ITEM_VENDA
-- ============================================================
CREATE TABLE item_venda (
    id_item_venda INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_venda INTEGER NOT NULL,
    id_produto INTEGER NOT NULL,
    quantidade INTEGER NOT NULL,
    preco_praticado DECIMAL(10,2) NOT NULL,

    CONSTRAINT pk_item_venda
        PRIMARY KEY (id_item_venda),

    CONSTRAINT fk_item_venda_venda
        FOREIGN KEY (id_venda)
        REFERENCES venda (id_venda),

    CONSTRAINT fk_item_venda_produto
        FOREIGN KEY (id_produto)
        REFERENCES produto (id_produto),

    CONSTRAINT uq_item_venda_produto
        UNIQUE (id_venda, id_produto),

    CONSTRAINT ck_item_venda_quantidade
        CHECK (quantidade > 0),

    CONSTRAINT ck_item_venda_preco
        CHECK (preco_praticado > 0)
);

-- ============================================================
-- 9. MOV_ESTOQUE
-- ============================================================
CREATE TABLE mov_estoque (
    id_mov_estoque INTEGER GENERATED BY DEFAULT AS IDENTITY,
